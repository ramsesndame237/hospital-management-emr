// Génère, depuis migration/inventory/entities.json :
//   - src/database/entities/<module>.entities.ts  (entités TypeORM, un fichier par module)
//   - src/database/entities/index.ts              (liste ALL_ENTITIES)
//   - migration/schema/schema.pg.sql              (DDL PostgreSQL équivalent)
// Conventions : tables et colonnes en snake_case dans PostgreSQL ; propriétés TypeScript en PascalCase d'origine, afin que
// le JSON renvoyé à l'Angular reste identique à celui du backend .NET (contrat d'API préservé).
//   node tools/generate-entities.mjs
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const inv = JSON.parse(fs.readFileSync(path.join(ROOT, 'migration/inventory/entities.json'), 'utf8'));
const ENT_DIR = path.join(ROOT, 'src/database/entities');
const SCHEMA_DIR = path.join(ROOT, 'migration/schema');
fs.rmSync(ENT_DIR, { recursive: true, force: true });
fs.mkdirSync(ENT_DIR, { recursive: true });
fs.mkdirSync(SCHEMA_DIR, { recursive: true });

export const snake = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2').replace(/[^A-Za-z0-9_]/g, '_').replace(/_+/g, '_').toLowerCase();
const kebab = (s) => snake(s).replace(/_/g, '-');
const moduleName = (folder) => kebab(folder.replace(/^DanpheEMR\./, '').replace(/Models?$/, '') || 'common');

const TS = { integer: 'number', smallint: 'number', bigint: 'number', numeric: 'number', 'double precision': 'number', real: 'number', boolean: 'boolean', text: 'string', timestamp: 'string', timestamptz: 'string', interval: 'string', uuid: 'string', bytea: 'Buffer' };
const NUMERIC = new Set(['bigint', 'numeric']);

const skipped = [];
const usedClass = new Map();
const byModule = new Map();
const ddl = [];
const colWarnings = [];

for (const e of inv.entities) {
  if (!e.pk.length) { skipped.push({ model: e.model, table: e.table, reason: 'aucune clé primaire détectée' }); continue; }
  const mod = moduleName(e.folder);
  let cls = e.model.replace(/[^A-Za-z0-9_]/g, '_');
  if (usedClass.has(cls)) cls = `${cls}_${snake(e.table)}`;
  usedClass.set(cls, e.table);
  const table = snake(e.table);
  const seen = new Set();
  const cols = [];
  for (const c of e.columns) {
    let col = snake(c.column);
    if (seen.has(col)) { colWarnings.push(`${e.table}: colonne dupliquée ${col} (${c.prop})`); col = `${col}_${snake(c.prop)}`; }
    seen.add(col);
    cols.push({ ...c, col, isPk: e.pk.includes(c.prop) });
  }
  if (!cols.some((c) => c.isPk)) { skipped.push({ model: e.model, table: e.table, reason: `clé ${e.pk.join(',')} absente des colonnes mappées` }); continue; }
  const singleIntPk = e.pk.length === 1 && ['integer', 'bigint', 'smallint'].includes(cols.find((c) => c.isPk).pgType);

  // ── entité TypeORM
  const lines = [`@Entity({ name: '${table}' })`, `export class ${cls} {`];
  for (const c of cols) {
    const opts = [`name: '${c.col}'`];
    const pgType = c.pgType === 'text' && c.maxLength ? `varchar` : c.pgType;
    const typeOpt = c.pgType === 'text' && c.maxLength ? `type: 'varchar', length: ${c.maxLength}` : `type: '${c.pgType}'`;
    let decorator;
    if (c.isPk && singleIntPk && c.generated !== 'None') {
      decorator = `@PrimaryGeneratedColumn({ ${opts.join(', ')}${c.pgType === 'integer' ? '' : `, type: '${c.pgType}'`} })`;
    } else if (c.isPk) {
      decorator = `@PrimaryColumn({ ${opts.join(', ')}, ${typeOpt}${NUMERIC.has(c.pgType) ? ', transformer: NUM' : ''} })`;
    } else {
      decorator = `@Column({ ${opts.join(', ')}, ${typeOpt}, nullable: ${c.nullable ? 'true' : 'false'}${NUMERIC.has(c.pgType) ? ', transformer: NUM' : ''} })`;
    }
    lines.push(`  ${decorator}`, `  ${c.prop}!: ${TS[c.pgType]}${c.nullable && !c.isPk ? ' | null' : ''};`, '');
  }
  lines.push('}', '');
  (byModule.get(mod) || byModule.set(mod, []).get(mod)).push({ cls, code: lines.join('\n') });

  // ── DDL PostgreSQL
  const defs = cols.map((c) => {
    const type = c.pgType === 'text' && c.maxLength ? `varchar(${c.maxLength})` : c.pgType;
    const ident = c.isPk && singleIntPk && c.generated !== 'None' ? ' GENERATED BY DEFAULT AS IDENTITY' : '';
    return `  "${c.col}" ${type}${ident}${c.nullable && !c.isPk ? '' : ' NOT NULL'}`;
  });
  defs.push(`  PRIMARY KEY (${cols.filter((c) => c.isPk).map((c) => `"${c.col}"`).join(', ')})`);
  ddl.push(`CREATE TABLE IF NOT EXISTS "${table}" (\n${defs.join(',\n')}\n);`);
}

const header = (extra) => `/* GÉNÉRÉ par tools/generate-entities.mjs depuis migration/inventory/entities.json : ne pas modifier à la main. */\nimport { Column, Entity, PrimaryColumn, PrimaryGeneratedColumn } from 'typeorm';\n${extra}\n`;
const index = [];
for (const [mod, items] of [...byModule.entries()].sort()) {
  const needsNum = items.some((i) => i.code.includes('transformer: NUM'));
  const body = header(needsNum ? "import { NUM } from '../transformers';" : '') + '\n' + items.map((i) => i.code).join('\n');
  fs.writeFileSync(path.join(ENT_DIR, `${mod}.entities.ts`), body);
  index.push({ mod, names: items.map((i) => i.cls) });
}
fs.writeFileSync(path.join(ENT_DIR, 'index.ts'),
  `/* GÉNÉRÉ par tools/generate-entities.mjs. */\n${index.map((x) => `import { ${x.names.join(', ')} } from './${x.mod}.entities';`).join('\n')}\n\nexport const ALL_ENTITIES = [\n${index.map((x) => `  ${x.names.join(', ')},`).join('\n')}\n];\n`);
fs.writeFileSync(path.join(SCHEMA_DIR, 'schema.pg.sql'), `-- GÉNÉRÉ par tools/generate-entities.mjs : schéma PostgreSQL déduit des modèles C# (code-first).\n-- Sera confronté au schéma réel SQL Server une fois la sauvegarde restaurée.\n\n${ddl.join('\n\n')}\n`);
fs.writeFileSync(path.join(ROOT, 'migration/inventory/entity-generation-report.json'), JSON.stringify({ generated: ddl.length, modules: index.length, skipped, columnWarnings: colWarnings }, null, 1));
console.log(`${ddl.length} tables générées dans ${index.length} modules ; ${skipped.length} ignorées ; ${colWarnings.length} colonnes dupliquées`);
